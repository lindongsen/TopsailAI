#!/usr/bin/env bash
# Live test for the scheduler, driven through the mock provider.
#
# This is a safe live test: it starts the real daemon, runs real tasks, and
# asserts every configuration detail the scheduler is supposed to deliver. The
# mock provider records the request document it received, so each assertion is
# made against what the scheduler actually sent rather than against a log line
# that merely claims it did.
#
# Nothing here needs an agent binary, a network or credentials, so it can run
# anywhere the Go toolchain runs.
#
# What is verified:
#
#   - the protocol version and the task identity (id, content path, folder)
#   - every placeholder expansion
#   - the task's own environment variables
#   - the workspace, both explicit and defaulted
#   - the timeout, both explicit and defaulted
#   - provider selection, both explicit and defaulted
#   - the lock preventing a second concurrent run
#   - the timeout actually ending a run
#   - restart reconciliation: a run left in flight by a killed supervisor is not
#     started a second time, and its record is cleared once it is confirmed over

set -u

# PROJECT_ROOT is the repository root, derived from this file's location.
PROJECT_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
# BINARY is the scheduler built by the Makefile.
BINARY="${PROJECT_ROOT}/.tmp/topsailai_scheduler"
# WORKSPACE is the temporary project folder the daemon runs in.
WORKSPACE="${PROJECT_ROOT}/.tmp/live"
# TASKS_ROOT is the task tree under test.
TASKS_ROOT="${WORKSPACE}/tasks"
# MOCK_PROVIDER is the mock provider executable the daemon runs by default.
MOCK_PROVIDER="${PROJECT_ROOT}/providers/mock/bin/mock"
# MOCK_STATE_DIR holds the mock provider's run records and request documents.
MOCK_STATE_DIR="${WORKSPACE}/mock-state"
# DAEMON_LOG captures the daemon's stdout and stderr.
DAEMON_LOG="${WORKSPACE}/daemon.log"
# EXIT_FILE records the daemon's exit code, because tmux does not propagate it.
EXIT_FILE="${WORKSPACE}/daemon.exit"

# daemon_pids prints the pid of every running scheduler daemon.
#
# The pattern is anchored to the exact command line on purpose. An unanchored
# `pgrep -f "<binary> run"` also matches the tmux wrapper whose command line
# merely contains that string, and the wrapper appears first. Signalling the
# wrapper kills the shell without forwarding the signal, so the daemon survives
# and never writes its exit code.
daemon_pids() {
	pgrep -f "^${BINARY} run$" 2>/dev/null
}

# SESSION is the deterministic tmux session name.
SESSION="sched-live"
# CLI_OUT captures the last CLI output.
CLI_OUT="${WORKSPACE}/cli.out"

# FAILURES counts failed assertions so the run can report a summary.
FAILURES=0
# CHECKS counts executed assertions.
CHECKS=0

# log prints a progress line.
log() {
	printf '[live] %s\n' "$*"
}

# pass records a successful assertion.
pass() {
	CHECKS=$((CHECKS + 1))
	printf '[live] ok: %s\n' "$*"
}

# fail records a failed assertion.
fail() {
	CHECKS=$((CHECKS + 1))
	FAILURES=$((FAILURES + 1))
	printf '[live] FAIL: %s\n' "$*" >&2
}

# assert_equals fails unless both values match.
assert_equals() {
	local expected="$1"
	local actual="$2"
	local description="$3"
	if [ "${expected}" = "${actual}" ]; then
		pass "${description}"
		return 0
	fi
	fail "${description}: want '${expected}', got '${actual}'"
	return 1
}

# assert_contains fails unless the file contains the pattern.
assert_contains() {
	local file="$1"
	local pattern="$2"
	local description="$3"
	if grep -qF -- "${pattern}" "${file}" 2>/dev/null; then
		pass "${description}"
		return 0
	fi
	fail "${description}: ${file} does not contain '${pattern}'"
	return 1
}

# json_get prints one value from a JSON document.
#
# A dotted expression walks objects and indexes lists, so "args.2" reads the
# third argument. A string is printed raw; anything else is printed as canonical
# JSON, so a map or list can be compared as one value.
json_get() {
	local file="$1"
	local expression="$2"
	python3 - "${file}" "${expression}" <<'PY'
import json
import sys

path, expression = sys.argv[1], sys.argv[2]
try:
    with open(path, "r", encoding="utf-8") as handle:
        value = json.load(handle)
except (OSError, ValueError):
    sys.exit(1)

for part in expression.split("."):
    if part == "":
        continue
    if isinstance(value, list):
        value = value[int(part)]
    else:
        value = value[part]

if isinstance(value, str):
    print(value)
else:
    print(json.dumps(value, sort_keys=True))
PY
}

# request_for_task prints the newest request document recorded for a task.
#
# The run id is generated by the provider, so a task is located by the identity
# the scheduler sent rather than by a name the test would have to guess.
request_for_task() {
	local task_id="$1"
	python3 - "${MOCK_STATE_DIR}" "${task_id}" <<'PY'
import glob
import json
import os
import sys

folder, task_id = sys.argv[1], sys.argv[2]
newest = None
for path in glob.glob(os.path.join(folder, "*.request.json")):
    try:
        with open(path, "r", encoding="utf-8") as handle:
            document = json.load(handle)
    except (OSError, ValueError):
        continue
    if document.get("task_id") != task_id:
        continue
    stamp = os.path.getmtime(path)
    if newest is None or stamp > newest[0]:
        newest = (stamp, path)
if newest is None:
    sys.exit(1)
print(newest[1])
PY
}

# count_requests prints how many request documents exist for a task.
count_requests() {
	local task_id="$1"
	python3 - "${MOCK_STATE_DIR}" "${task_id}" <<'PY'
import glob
import json
import os
import sys

folder, task_id = sys.argv[1], sys.argv[2]
total = 0
for path in glob.glob(os.path.join(folder, "*.request.json")):
    try:
        with open(path, "r", encoding="utf-8") as handle:
            document = json.load(handle)
    except (OSError, ValueError):
        continue
    if document.get("task_id") == task_id:
        total += 1
print(total)
PY
}

# wait_for_request polls until a request document exists for a task.
wait_for_request() {
	local task_id="$1"
	local timeout_seconds="${2:-20}"
	local waited=0
	while [ "${waited}" -lt $((timeout_seconds * 10)) ]; do
		if request_for_task "${task_id}" >/dev/null 2>&1; then
			return 0
		fi
		sleep 0.1
		waited=$((waited + 1))
	done
	return 1
}

# write_task writes the YAML and Markdown files of one task.
write_task() {
	local id="$1"
	local yaml_content="$2"
	local markdown_content="$3"
	mkdir -p "$(dirname "${TASKS_ROOT}/${id}")"
	printf '%s' "${yaml_content}" >"${TASKS_ROOT}/${id}.yaml"
	printf '%s' "${markdown_content}" >"${TASKS_ROOT}/${id}.md"
}

# scheduler_cli runs the CLI inside the workspace so it finds the same socket.
scheduler_cli() {
	(cd "${WORKSPACE}" && "${BINARY}" "$@")
}

# prepare_workspace recreates the temporary project folder.
prepare_workspace() {
	if [ -d "${WORKSPACE}" ]; then
		rm -rf "${WORKSPACE}"
		log "removed previous workspace ${WORKSPACE}"
	fi
	mkdir -p "${TASKS_ROOT}" "${MOCK_STATE_DIR}"
	: >"${DAEMON_LOG}"
	: >"${EXIT_FILE}"
}

# write_tasks writes the task tree the assertions are made against.
write_tasks() {
	# A task that names every configurable field, so each one can be asserted.
	# The extra arguments carry the placeholders; /bin/sh ignores them beyond
	# $0, so they are harmless while still proving the expansion.
	write_task "data/work" \
		'schedule: "0 8 * * *"
launcher: command
provider: '"${MOCK_PROVIDER}"'
command: /bin/sh
args: ["-c", "pwd > {task_dir}/pwd.txt", "{task}", "{task_id}", "{task_dir}", "{stem}", "{workspace}"]
workspace: /tmp
timeout: 45s
env:
  LIVE_ALPHA: "one"
  LIVE_BETA: "two"
' \
		'# Work task

Names every configurable field so each one can be asserted.
'

	# A task that names nothing optional, so the defaults can be asserted.
	write_task "defaults/plain" \
		'schedule: "0 8 * * *"
launcher: command
command: /bin/sh
args: ["-c", "true"]
' \
		'# Plain task

Relies on every default.
'

	# A deeply nested task, to prove nesting depth is unlimited.
	write_task "daily/nightly/report" \
		'schedule: "0 3 * * *"
launcher: command
command: /bin/sh
args: ["-c", "true"]
' \
		'# Report task

Proves nesting depth is unlimited.
'

	# A task that outlives its timeout, to prove the timeout ends the run.
	write_task "slow/timeout" \
		'schedule: "0 8 * * *"
launcher: command
command: /bin/sh
args: ["-c", "sleep 120"]
timeout: 2s
' \
		'# Timeout task

Sleeps far longer than its timeout.
'

	# A task that sleeps, so a second launch overlaps it.
	write_task "slow/locked" \
		'schedule: "0 8 * * *"
launcher: command
command: /bin/sh
args: ["-c", "sleep 30"]
' \
		'# Locked task

Sleeps so a second launch overlaps.
'

	# A task that sleeps long enough to outlive a killed supervisor, so restart
	# reconciliation can be exercised against a genuinely running run.
	write_task "slow/reconcile" \
		'schedule: "0 8 * * *"
launcher: command
command: /bin/sh
args: ["-c", "sleep 10"]
' \
		'# Reconcile task

Outlives a killed supervisor so the restart can reconcile it.
'
}

# start_daemon launches the daemon inside tmux with output captured to disk.
start_daemon() {
	tmux kill-session -t "${SESSION}" 2>/dev/null && log "killed a stale session ${SESSION}"

	# The exit code is written by the wrapper because tmux does not propagate it.
	local command
	command="cd '${WORKSPACE}' && SCHEDULER_TASKS_ROOT='${TASKS_ROOT}' \
SCHEDULER_CONTROL_SOCKET='${WORKSPACE}/scheduler.sock' \
SCHEDULER_LOG_OUTPUT='${DAEMON_LOG}' \
SCHEDULER_LOG_LEVEL=debug \
SCHEDULER_RESCAN_INTERVAL=1s \
SCHEDULER_SHUTDOWN_GRACE=5s \
SCHEDULER_DEFAULT_TIMEOUT=30s \
SCHEDULER_DEFAULT_PROVIDER_PATH='${MOCK_PROVIDER}' \
SCHEDULER_POLL_INTERVAL=100ms \
MOCK_PROVIDER_STATE_DIR='${MOCK_STATE_DIR}' \
'${BINARY}' run; echo \$? >'${EXIT_FILE}'"

	tmux new-session -d -s "${SESSION}" "${command}"
	log "started session ${SESSION}"
}

# wait_for_ready polls the log for the readiness line.
wait_for_ready() {
	local waited=0
	while [ "${waited}" -lt 200 ]; do
		if grep -qF -- "scheduler starting" "${DAEMON_LOG}" 2>/dev/null; then
			pass "the daemon reported startup"
			return 0
		fi
		sleep 0.1
		waited=$((waited + 1))
	done
	fail "the daemon did not report startup"
	return 1
}

# wait_for_socket polls until the control socket answers.
wait_for_socket() {
	local waited=0
	while [ "${waited}" -lt 200 ]; do
		if scheduler_cli status >/dev/null 2>&1; then
			pass "the control socket answered"
			return 0
		fi
		sleep 0.1
		waited=$((waited + 1))
	done
	fail "the control socket did not answer"
	return 1
}

# check_task_identity verifies the identity the scheduler sends for a task.
check_task_identity() {
	log "checking the task identity"
	local request
	if ! request="$(request_for_task "data/work")"; then
		fail "no request was recorded for data/work"
		return 1
	fi

	assert_equals "1" "$(json_get "${request}" protocol_version)" \
		"the protocol version is 1"
	assert_equals "data/work" "$(json_get "${request}" task_id)" \
		"the task id is the relative path without the suffix"
	assert_equals "${TASKS_ROOT}/data/work.md" "$(json_get "${request}" task_path)" \
		"the task path is the absolute Markdown path"
	assert_equals "${TASKS_ROOT}/data" "$(json_get "${request}" task_dir)" \
		"the task folder is the absolute parent folder"
}

# check_placeholders verifies every placeholder is expanded before the run.
check_placeholders() {
	log "checking the placeholder expansion"
	local request
	if ! request="$(request_for_task "data/work")"; then
		fail "no request was recorded for data/work"
		return 1
	fi

	assert_equals "${TASKS_ROOT}/data/work.md" "$(json_get "${request}" args.2)" \
		"{task} expands to the Markdown path"
	assert_equals "data/work" "$(json_get "${request}" args.3)" \
		"{task_id} expands to the task id"
	assert_equals "${TASKS_ROOT}/data" "$(json_get "${request}" args.4)" \
		"{task_dir} expands to the task folder"
	assert_equals "work" "$(json_get "${request}" args.5)" \
		"{stem} expands to the shared filename stem"
	assert_equals "/tmp" "$(json_get "${request}" args.6)" \
		"{workspace} expands to the resolved workspace"
	assert_equals "pwd > ${TASKS_ROOT}/data/pwd.txt" "$(json_get "${request}" args.1)" \
		"a placeholder inside a longer argument is expanded in place"
}

# check_environment verifies the task's own environment reaches the provider.
check_environment() {
	log "checking the task environment"
	local request
	if ! request="$(request_for_task "data/work")"; then
		fail "no request was recorded for data/work"
		return 1
	fi

	assert_equals '{"LIVE_ALPHA": "one", "LIVE_BETA": "two"}' \
		"$(json_get "${request}" env)" \
		"the task's environment variables are sent unchanged"
}

# check_workspace verifies the workspace is explicit when set and defaulted when
# not.
check_workspace() {
	log "checking the workspace"
	local request
	if ! request="$(request_for_task "data/work")"; then
		fail "no request was recorded for data/work"
		return 1
	fi
	assert_equals "/tmp" "$(json_get "${request}" workspace)" \
		"an explicit workspace is sent"

	if ! request="$(request_for_task "defaults/plain")"; then
		fail "no request was recorded for defaults/plain"
		return 1
	fi
	assert_equals "${WORKSPACE}" "$(json_get "${request}" workspace)" \
		"a task without a workspace gets the scheduler default"
}

# check_timeout verifies the timeout is explicit when set and defaulted when not.
check_timeout() {
	log "checking the timeout"
	local request
	if ! request="$(request_for_task "data/work")"; then
		fail "no request was recorded for data/work"
		return 1
	fi
	assert_equals "45000" "$(json_get "${request}" timeout_ms)" \
		"an explicit timeout is sent in milliseconds"

	if ! request="$(request_for_task "defaults/plain")"; then
		fail "no request was recorded for defaults/plain"
		return 1
	fi
	assert_equals "30000" "$(json_get "${request}" timeout_ms)" \
		"a task without a timeout gets the scheduler default"
}

# check_defaults verifies a task that names nothing optional still sends a
# complete request.
check_defaults() {
	log "checking the defaults"
	local request
	if ! request="$(request_for_task "defaults/plain")"; then
		fail "no request was recorded for defaults/plain"
		return 1
	fi

	assert_equals "/bin/sh" "$(json_get "${request}" command)" \
		"the command launcher sends the task's executable"
	assert_equals "null" "$(json_get "${request}" env)" \
		"a task without environment variables sends none"
	assert_equals "defaults/plain" "$(json_get "${request}" task_id)" \
		"the default provider receives the task identity"
}

# check_nesting verifies a deeply nested task keeps its relative identity.
check_nesting() {
	log "checking the nesting"
	local request
	if ! request="$(request_for_task "daily/nightly/report")"; then
		fail "no request was recorded for daily/nightly/report"
		return 1
	fi

	assert_equals "daily/nightly/report" "$(json_get "${request}" task_id)" \
		"a deeply nested task keeps its relative id"
	assert_equals "${TASKS_ROOT}/daily/nightly" "$(json_get "${request}" task_dir)" \
		"a deeply nested task reports its own folder"
}

# check_run_executes_in_the_workspace verifies the run really ran where the
# scheduler said it should.
check_run_executes_in_the_workspace() {
	log "checking the run location"
	local marker="${TASKS_ROOT}/data/pwd.txt"
	local waited=0
	while [ "${waited}" -lt 100 ]; do
		if [ -s "${marker}" ]; then
			break
		fi
		sleep 0.1
		waited=$((waited + 1))
	done
	if [ ! -s "${marker}" ]; then
		fail "the run did not write ${marker}"
		return 1
	fi
	assert_equals "/tmp" "$(tr -d '\n' <"${marker}")" \
		"the run executed in the workspace the scheduler named"
}

# check_lock verifies a second launch of a running task starts no new run.
check_lock() {
	log "checking the lock"
	scheduler_cli launch slow/locked >"${CLI_OUT}" 2>&1
	assert_equals "0" "$?" "the first launch succeeds"

	if ! wait_for_request "slow/locked" 20; then
		fail "the first launch recorded no request"
		return 1
	fi

	scheduler_cli launch slow/locked >"${CLI_OUT}" 2>&1
	assert_contains "${CLI_OUT}" "already running" "the second launch is skipped"
	assert_equals "1" "$(count_requests "slow/locked")" \
		"the skipped launch sent no request to the provider"

	scheduler_cli stop slow/locked >"${CLI_OUT}" 2>&1
	assert_equals "0" "$?" "the running task can be stopped"
}

# check_timeout_ends_the_run verifies a run exceeding its timeout is ended.
check_timeout_ends_the_run() {
	log "checking the timeout enforcement"
	scheduler_cli launch slow/timeout --wait >"${CLI_OUT}" 2>&1
	assert_contains "${CLI_OUT}" "timed out: yes" "the run reports a timeout"
	assert_contains "${DAEMON_LOG}" "run timed out" "the timeout is logged"
}


# check_restart_reconciliation verifies a run left in flight by a killed
# supervisor is not started a second time after the restart.
#
# The scenario is a real crash, not a simulated one: the daemon is killed with
# SIGKILL while a run is in flight, so it cannot clean up. The run itself is
# detached into its own process group, so it survives. After the restart the lock
# is free, and only the record the dead supervisor left in the lock file says
# that something is still working. Without reconciliation the next launch would
# start a duplicate copy of the same task.
check_restart_reconciliation() {
	log "checking restart reconciliation"

	scheduler_cli launch slow/reconcile >"${CLI_OUT}" 2>&1
	assert_equals "0" "$?" "the reconcilable task starts"

	if ! wait_for_request "slow/reconcile" 20; then
		fail "the reconcilable task recorded no request"
		return 1
	fi

	# The record must exist before the crash, otherwise the restart has nothing
	# to reconcile and the check would pass for the wrong reason.
	local lock_file="${TASKS_ROOT}/slow/reconcile.lock"
	local waited=0
	while [ "${waited}" -lt 100 ]; do
		if [ -s "${lock_file}" ]; then
			break
		fi
		sleep 0.1
		waited=$((waited + 1))
	done
	if [ ! -s "${lock_file}" ]; then
		fail "the supervisor wrote no record into ${lock_file}"
		return 1
	fi
	pass "the supervisor recorded the run in the lock file"

	local recorded_run_id
	recorded_run_id="$(json_get "${lock_file}" run_id)"
	assert_equals "${MOCK_PROVIDER}" "$(json_get "${lock_file}" provider)" \
		"the record names the provider that owns the run"
	if [ -z "${recorded_run_id}" ]; then
		fail "the record carries no run id"
		return 1
	fi

	# SIGKILL, not SIGTERM: a graceful stop would clear the record and there
	# would be nothing left to reconcile.
	local daemon_pid
	daemon_pid="$(daemon_pids | head -1)"
	if [ -z "${daemon_pid}" ]; then
		fail "the daemon pid was not found"
		return 1
	fi
	kill -KILL "${daemon_pid}"
	waited=0
	while [ "${waited}" -lt 100 ]; do
		if ! kill -0 "${daemon_pid}" 2>/dev/null; then
			break
		fi
		sleep 0.1
		waited=$((waited + 1))
	done
	if kill -0 "${daemon_pid}" 2>/dev/null; then
		fail "the daemon survived SIGKILL"
		return 1
	fi
	pass "the daemon was killed while the run was in flight"

	# The record must outlive the supervisor, otherwise the restart has no
	# breadcrumb and the whole mechanism is pointless.
	assert_equals "${recorded_run_id}" "$(json_get "${lock_file}" run_id)" \
		"the record survives the supervisor that wrote it"

	# Restart. The run is still sleeping, so the provider still reports running.
	start_daemon
	if ! wait_for_ready; then
		return 1
	fi
	if ! wait_for_socket; then
		return 1
	fi

	local before
	before="$(count_requests "slow/reconcile")"

	scheduler_cli launch slow/reconcile >"${CLI_OUT}" 2>&1
	assert_contains "${CLI_OUT}" "already running" \
		"the launch is skipped while the recorded run is still working"
	assert_equals "${before}" "$(count_requests "slow/reconcile")" \
		"the skipped launch sent no second start to the provider"
	assert_contains "${DAEMON_LOG}" "a run from a previous supervisor is still in flight" \
		"the skip is logged as a reconciliation, not as a plain lock conflict"

	# The record must still be there: the run was never confirmed finished, so
	# clearing it would lose the only evidence that it is still working.
	assert_equals "${recorded_run_id}" "$(json_get "${lock_file}" run_id)" \
		"the record is kept while the run is unconfirmed"

	# The orphaned run ends on its own. Waiting for its exit file is what makes
	# the next step a real reconciliation of a finished run rather than a guess.
	local exit_file="${MOCK_STATE_DIR}/${recorded_run_id}.exit"
	waited=0
	while [ "${waited}" -lt 300 ]; do
		if [ -s "${exit_file}" ]; then
			break
		fi
		sleep 0.1
		waited=$((waited + 1))
	done
	if [ ! -s "${exit_file}" ]; then
		fail "the orphaned run did not finish on its own"
		return 1
	fi
	pass "the orphaned run finished on its own"

	# A run that is over must not block the task forever: the next launch
	# reconciles it as finished, clears the record and starts a fresh run.
	scheduler_cli launch slow/reconcile >"${CLI_OUT}" 2>&1
	assert_contains "${CLI_OUT}" "started" \
		"a finished recorded run no longer blocks the task"
	assert_equals "$((before + 1))" "$(count_requests "slow/reconcile")" \
		"the reconciled launch started exactly one new run"

	local new_run_id
	new_run_id="$(json_get "${lock_file}" run_id)"
	if [ "${new_run_id}" = "${recorded_run_id}" ]; then
		fail "the record still names the finished run"
		return 1
	fi
	pass "the record now names the new run"

	scheduler_cli stop slow/reconcile >"${CLI_OUT}" 2>&1
	assert_equals "0" "$?" "the new run can be stopped"
}

# check_shutdown verifies SIGTERM stops the daemon and leaves no orphan.
check_shutdown() {
	log "checking shutdown"
	local daemon_pid
	daemon_pid="$(daemon_pids | head -1)"
	if [ -z "${daemon_pid}" ]; then
		fail "the daemon pid was not found"
		return 1
	fi

	kill -TERM "${daemon_pid}"

	local waited=0
	while [ "${waited}" -lt 100 ]; do
		if ! kill -0 "${daemon_pid}" 2>/dev/null; then
			break
		fi
		sleep 0.1
		waited=$((waited + 1))
	done
	if kill -0 "${daemon_pid}" 2>/dev/null; then
		fail "the daemon is still alive after SIGTERM"
	else
		pass "the daemon exited after SIGTERM"
	fi

	waited=0
	while [ "${waited}" -lt 100 ]; do
		if [ -s "${EXIT_FILE}" ]; then
			break
		fi
		sleep 0.1
		waited=$((waited + 1))
	done
	assert_equals "0" "$(cat "${EXIT_FILE}" 2>/dev/null)" "the daemon exited with code 0"

	local orphans
	orphans="$(daemon_pids | wc -l)"
	assert_equals "0" "${orphans}" "no daemon process survived"
}

# summary prints the assertion summary and returns non-zero on failure.
summary() {
	printf '[live] %d checks, %d failures\n' "${CHECKS}" "${FAILURES}"
	if [ "${FAILURES}" -ne 0 ]; then
		return 1
	fi
	return 0
}

# cleanup removes the tmux session and the temporary workspace.
cleanup() {
	tmux kill-session -t "${SESSION}" 2>/dev/null && log "killed session ${SESSION}"
	if [ -d "${WORKSPACE}" ]; then
		rm -rf "${WORKSPACE}"
		log "removed workspace ${WORKSPACE}"
	fi
}

main() {
	if ! "${PROJECT_ROOT}/tests/binary_fresh.sh"; then
		fail "the scheduler binary is stale or missing"
		summary
		exit 1
	fi

	prepare_workspace
	write_tasks
	start_daemon

	if ! wait_for_ready; then
		summary
		tmux kill-session -t "${SESSION}" 2>/dev/null
		exit 1
	fi
	if ! wait_for_socket; then
		summary
		tmux kill-session -t "${SESSION}" 2>/dev/null
		exit 1
	fi

	# Launch the task that names every configurable field, then assert what the
	# provider received.
	scheduler_cli launch data/work --wait >"${CLI_OUT}" 2>&1
	assert_equals "0" "$?" "the fully configured task runs"

	scheduler_cli launch defaults/plain --wait >"${CLI_OUT}" 2>&1
	assert_equals "0" "$?" "the task relying on defaults runs"

	scheduler_cli launch daily/nightly/report --wait >"${CLI_OUT}" 2>&1
	assert_equals "0" "$?" "the deeply nested task runs"

	check_task_identity
	check_placeholders
	check_environment
	check_workspace
	check_timeout
	check_defaults
	check_nesting
	check_run_executes_in_the_workspace
	check_lock
	check_timeout_ends_the_run
	check_restart_reconciliation
	check_shutdown

	if summary; then
		cleanup
		exit 0
	fi
	# Keep the workspace on failure so the evidence can be inspected.
	tmux kill-session -t "${SESSION}" 2>/dev/null
	exit 1
}

main "$@"
