// watchFixture is a config directory holding an identity file, plus a dialer whose
// watcher can be driven directly.
type watchFixture struct {
	configDir    string
	identityPath string
	holder       *IdentityHolder
	dialer       *Dialer
	first        security.NodeIdentity
}

// newWatchFixture writes an identity file and builds a dialer over it.
//
// The dialer is built with a nil dispatcher authority, because the watcher never
// dispatches: it reads the file and updates the holder. A test that needed an
// authority would be testing the policy rather than the watch.
func newWatchFixture(t *testing.T) *watchFixture {
	t.Helper()

	configDir := t.TempDir()
	identityPath := IdentityPath(configDir)

	first, err := security.NewNodeIdentity()
	if err != nil {
		t.Fatalf("NewNodeIdentity() = %v, want nil", err)
	}
	if err := SaveIdentity(identityPath, first); err != nil {
		t.Fatalf("SaveIdentity() = %v, want nil", err)
	}

	holder := NewIdentityHolder(first)
	dispatcher := NewDispatcherWithHolder(nil, holder, slog.New(slog.DiscardHandler))
	dialer, err := NewDialerWithHolder(
		Config{ConfigDir: configDir},
		holder,
		dispatcher,
		slog.New(slog.DiscardHandler),
	)
	if err != nil {
		t.Fatalf("NewDialerWithHolder() = %v, want nil", err)
	}

	return &watchFixture{
		configDir:    configDir,
		identityPath: identityPath,
		holder:       holder,
		dialer:       dialer,
		first:        first,
	}
}

// regenerate replaces the identity file with a fresh pair and returns it.
func (f *watchFixture) regenerate(t *testing.T, keepID bool) security.NodeIdentity {
	t.Helper()
	next, err := RegenerateIdentity(f.identityPath, keepID)
	if err != nil {
		t.Fatalf("RegenerateIdentity() = %v, want nil", err)
	}
	return next
}

// waitForChange waits until the watcher signals a change or the deadline passes.
func waitForChange(t *testing.T, changes <-chan struct{}, timeout time.Duration) bool {
	t.Helper()
	select {
	case <-changes:
		return true
	case <-time.After(timeout):
		return false
	}
}

// TestWatchIdentityAdoptsARegeneratedPair checks the defect this mechanism exists
// to fix: a pair regenerated by another process is adopted by the running Node.
//
// Without the watcher the running process keeps the pair it read at startup, so
// the old token keeps working and the new one is refused. The assertion is on the
// holder rather than on a log line, because the holder is what the dispatcher
// compares a request against.
func TestWatchIdentityAdoptsARegeneratedPair(t *testing.T) {
	fixture := newWatchFixture(t)

	ctx, cancel := context.WithCancel(context.Background())
	defer cancel()

	changes := make(chan struct{}, 1)
	go fixture.dialer.watchIdentity(ctx, changes)

	next := fixture.regenerate(t, true)

	if !waitForChange(t, changes, 5*time.Second) {
		t.Fatal("the watcher never reported the regenerated pair")
	}

	current := fixture.holder.Current()
	if !current.Token.Equal(next.Token) {
		t.Fatal("the holder still carries the old token after a regeneration")
	}
	if current.ID != fixture.first.ID {
		t.Fatalf("Current().ID = %q, want %q for a --keep-id regeneration", current.ID, fixture.first.ID)
	}
}

// TestWatchIdentityAdoptsAFullyRegeneratedPair checks that a regeneration which
// changes both halves is adopted, because the identifier is what the Server routes
// by and the Node must announce the new one.
func TestWatchIdentityAdoptsAFullyRegeneratedPair(t *testing.T) {
	fixture := newWatchFixture(t)

	ctx, cancel := context.WithCancel(context.Background())
	defer cancel()

	changes := make(chan struct{}, 1)
	go fixture.dialer.watchIdentity(ctx, changes)

	next := fixture.regenerate(t, false)

	if !waitForChange(t, changes, 5*time.Second) {
		t.Fatal("the watcher never reported the regenerated pair")
	}
	if current := fixture.holder.Current(); current.ID != next.ID {
		t.Fatalf("Current().ID = %q, want %q after a full regeneration", current.ID, next.ID)
	}
}

// TestWatchIdentityIgnoresAnUnchangedFile checks that a rewrite producing the same
// pair does not drop the channel.
//
// The file is rewritten with the identical content, which changes the modification
// time. A watcher that signalled on every write would turn an unrelated touch into
// a reconnect, and a reconnect is a visible interruption for the operator.
func TestWatchIdentityIgnoresAnUnchangedFile(t *testing.T) {
	fixture := newWatchFixture(t)

	ctx, cancel := context.WithCancel(context.Background())
	defer cancel()

	changes := make(chan struct{}, 1)
	go fixture.dialer.watchIdentity(ctx, changes)

	// A rewrite with the same pair. The sleep guarantees the modification time
	// differs, so the watcher cannot pass the test by never noticing the write.
	time.Sleep(20 * time.Millisecond)
	if err := SaveIdentity(fixture.identityPath, fixture.first); err != nil {
		t.Fatalf("SaveIdentity() = %v, want nil", err)
	}

	if waitForChange(t, changes, 2500*time.Millisecond) {
		t.Fatal("the watcher reported a change for an identical pair, which would drop a working channel")
	}
	if current := fixture.holder.Current(); !current.Token.Equal(fixture.first.Token) {
		t.Fatal("the holder changed even though the file held the same pair")
	}
}

// TestWatchIdentityKeepsTheOldPairWhenTheFileIsMalformed checks that a corrupt
// file does not replace a working identity.
//
// Adopting a malformed file would leave the Node serving an identity it cannot
// parse, which is worse than serving the old one until the operator fixes the
// file. The old pair must stay in force and no change must be signalled.
func TestWatchIdentityKeepsTheOldPairWhenTheFileIsMalformed(t *testing.T) {
	fixture := newWatchFixture(t)

	ctx, cancel := context.WithCancel(context.Background())
	defer cancel()

	changes := make(chan struct{}, 1)
	go fixture.dialer.watchIdentity(ctx, changes)

	time.Sleep(20 * time.Millisecond)
	if err := os.WriteFile(fixture.identityPath, []byte("not-a-pair\n"), 0o600); err != nil {
		t.Fatalf("write a malformed identity file: %v", err)
	}

	if waitForChange(t, changes, 2500*time.Millisecond) {
		t.Fatal("the watcher reported a change for a malformed file")
	}
	if current := fixture.holder.Current(); !current.Token.Equal(fixture.first.Token) {
		t.Fatal("the holder adopted a malformed identity")
	}
}

// TestWatchIdentityKeepsTheOldPairWhenTheFileDisappears checks that a deleted file
// does not clear the identity.
//
// A Node whose identity file was removed by mistake must keep serving the pair it
// already holds rather than start refusing every request, because the operator's
// next action is to restore the file, not to re-provision the Node.
func TestWatchIdentityKeepsTheOldPairWhenTheFileDisappears(t *testing.T) {
	fixture := newWatchFixture(t)

	ctx, cancel := context.WithCancel(context.Background())
	defer cancel()

	changes := make(chan struct{}, 1)
	go fixture.dialer.watchIdentity(ctx, changes)

	time.Sleep(20 * time.Millisecond)
	if err := os.Remove(fixture.identityPath); err != nil {
		t.Fatalf("remove the identity file: %v", err)
	}

	if waitForChange(t, changes, 2500*time.Millisecond) {
		t.Fatal("the watcher reported a change for a missing file")
	}
	if current := fixture.holder.Current(); !current.Token.Equal(fixture.first.Token) {
		t.Fatal("the holder lost the identity when the file disappeared")
	}
}

// TestWatchIdentityStopsWithTheContext checks that the watcher returns when the
// context ends, because a shutdown must not leave a goroutine polling a file.
func TestWatchIdentityStopsWithTheContext(t *testing.T) {
	fixture := newWatchFixture(t)

	ctx, cancel := context.WithCancel(context.Background())
	changes := make(chan struct{}, 1)

	done := make(chan struct{})
	go func() {
		fixture.dialer.watchIdentity(ctx, changes)
		close(done)
	}()

	cancel()

	select {
	case <-done:
	case <-time.After(5 * time.Second):
		t.Fatal("the watcher did not stop after the context was cancelled")
	}
}

// TestWatchIdentityWithoutAPathReturnsImmediately checks that a dialer with no
// config directory does not start a poll loop.
//
// A dialer built by a test with an empty Config has no identity file to watch, and
// a watcher that polled anyway would be a goroutine doing nothing for the life of
// the process.
func TestWatchIdentityWithoutAPathReturnsImmediately(t *testing.T) {
	holder := NewIdentityHolder(security.NodeIdentity{ID: "node_0123456789abcdefghijklmnop", Token: security.Secret("token")})
	dispatcher := NewDispatcherWithHolder(nil, holder, slog.New(slog.DiscardHandler))
	dialer, err := NewDialerWithHolder(Config{}, holder, dispatcher, slog.New(slog.DiscardHandler))
	if err != nil {
		t.Fatalf("NewDialerWithHolder() = %v, want nil", err)
	}

	done := make(chan struct{})
	go func() {
		dialer.watchIdentity(context.Background(), make(chan struct{}, 1))
		close(done)
	}()

	select {
	case <-done:
	case <-time.After(2 * time.Second):
		t.Fatal("the watcher polled even though the dialer has no identity path")
	}
}

// TestWatchIdentityDetectsASameLengthRewrite pins the defect that made the
// previous mtime-and-size stamp unreliable.
//
// A regenerated pair is exactly the same length as the pair it replaces, and the
// rewrite can land in the same filesystem timestamp tick. A stamp built from
// mtime and size therefore reported "unchanged" for a file holding a different
// credential, so the running Node kept accepting the retired token. Comparing the
// content is what makes this case detectable.
func TestWatchIdentityDetectsASameLengthRewrite(t *testing.T) {
	fixture := newWatchFixture(t)

	ctx, cancel := context.WithCancel(context.Background())
	defer cancel()

	changes := make(chan struct{}, 1)
	go fixture.dialer.watchIdentity(ctx, changes)

	// The replacement is written directly rather than through RegenerateIdentity,
	// so the test controls the encoded length and can assert that the two pairs
	// are the same size. A size comparison cannot distinguish them.
	next, err := security.NewNodeIdentity()
	if err != nil {
		t.Fatalf("NewNodeIdentity() = %v, want nil", err)
	}
	if len(string(next.Token)) != len(string(fixture.first.Token)) {
		t.Fatalf("the fixture tokens differ in length (%d and %d), so this test would not exercise the same-length case",
			len(string(next.Token)), len(string(fixture.first.Token)))
	}
	if err := SaveIdentity(fixture.identityPath, next); err != nil {
		t.Fatalf("SaveIdentity() = %v, want nil", err)
	}

	if !waitForChange(t, changes, 5*time.Second) {
		t.Fatal("a same-length rewrite was not detected, so the running Node would keep accepting the retired token")
	}

	if current := fixture.holder.Current(); !current.Token.Equal(next.Token) {
		t.Fatal("the holder kept the retired token after a same-length rewrite")
	}
}

// TestDiscardPendingIdentityChangeDrainsOneSignal checks that a signal left over
// from a disconnected period is removed before the next dial.
//
// Without the drain, a regeneration during a reconnect delay would drop the
// freshly established channel even though it was authenticated with the new pair.
func TestDiscardPendingIdentityChangeDrainsOneSignal(t *testing.T) {
	changes := make(chan struct{}, 1)
	changes <- struct{}{}

	discardPendingIdentityChange(changes)

	select {
	case <-changes:
		t.Fatal("a signal survived the drain, so the next channel would be dropped")
	default:
	}
}

// TestDiscardPendingIdentityChangeToleratesAnEmptyChannel checks that the drain
// does not block when nothing is pending, because it runs on every loop iteration.
func TestDiscardPendingIdentityChangeToleratesAnEmptyChannel(t *testing.T) {
	changes := make(chan struct{}, 1)

	done := make(chan struct{})
	go func() {
		discardPendingIdentityChange(changes)
		close(done)
	}()

	select {
	case <-done:
	case <-time.After(2 * time.Second):
		t.Fatal("the drain blocked on an empty channel")
	}
}
