// watchFixture is a config directory holding an identity file and a credential file,
// plus a dialer whose watcher can be driven directly.
type watchFixture struct {
	configDir       string
	identityPath    string
	credentialsPath string
	holder          *IdentityHolder
	dialer          *Dialer
	firstID         string
	firstCredential security.Credential
}

// newWatchFixture writes an identity file and a credential file, then builds a dialer
// over them.
//
// The dialer is built with a nil dispatcher authority, because the watcher never
// dispatches: it reads the files and updates the holder. A test that needed an
// authority would be testing the policy rather than the watch.
func newWatchFixture(t *testing.T) *watchFixture {
	t.Helper()

	configDir := t.TempDir()
	identityPath := IdentityPath(configDir)
	credentialsPath := CredentialsPath(configDir)

	firstID, err := security.NewNodeID()
	if err != nil {
		t.Fatalf("NewNodeID() = %v, want nil", err)
	}
	if err := SaveIdentity(identityPath, firstID); err != nil {
		t.Fatalf("SaveIdentity() = %v, want nil", err)
	}

	firstCredential, err := security.NewCredentialWithKeyID("first-caller")
	if err != nil {
		t.Fatalf("NewCredentialWithKeyID() = %v, want nil", err)
	}
	if err := SaveCredentials(credentialsPath, []security.Credential{firstCredential}); err != nil {
		t.Fatalf("SaveCredentials() = %v, want nil", err)
	}

	credentials, err := LoadCredentials(credentialsPath)
	if err != nil {
		t.Fatalf("LoadCredentials() = %v, want nil", err)
	}
	holder := NewIdentityHolder(firstID, credentials)
	dispatcher, err := NewDispatcher(nil, holder, security.DefaultReplayWindow, security.DefaultReplayCapacity, slog.New(slog.DiscardHandler))
	if err != nil {
		t.Fatalf("NewDispatcher() = %v, want nil", err)
	}
	dialer, err := NewDialerWithHolder(
		Config{ConfigDir: configDir},
		holder,
		dispatcher,
		slog.New(slog.DiscardHandler),
	)
	if err != nil {
		t.Fatalf("NewDialerWithHolder() = %v, want nil", err)
	}

	return &watchFixture{
		configDir:       configDir,
		identityPath:    identityPath,
		credentialsPath: credentialsPath,
		holder:          holder,
		dialer:          dialer,
		firstID:         firstID,
		firstCredential: firstCredential,
	}
}

// regenerate replaces the identity file with a fresh node id and returns it.
func (f *watchFixture) regenerate(t *testing.T) string {
	t.Helper()
	next, err := RegenerateIdentity(f.identityPath)
	if err != nil {
		t.Fatalf("RegenerateIdentity() = %v, want nil", err)
	}
	return next
}

// waitForChange waits until the watcher signals a change or the deadline passes.
func waitForChange(t *testing.T, changes <-chan struct{}, timeout time.Duration) bool {
	t.Helper()
	select {
	case <-changes:
		return true
	case <-time.After(timeout):
		return false
	}
}

// TestWatchIdentityAdoptsARegeneratedNodeID checks the defect this mechanism exists to
// fix: a node id regenerated by another process is adopted by the running Node.
//
// Without the watcher the running process keeps the id it read at startup, so the old
// address keeps working and the new one is refused. The assertion is on the holder
// rather than on a log line, because the holder is what the dispatcher compares a
// request against.
func TestWatchIdentityAdoptsARegeneratedNodeID(t *testing.T) {
	fixture := newWatchFixture(t)

	ctx, cancel := context.WithCancel(context.Background())
	defer cancel()

	changes := make(chan struct{}, 1)
	go fixture.dialer.watchIdentity(ctx, changes)

	next := fixture.regenerate(t)

	if !waitForChange(t, changes, 5*time.Second) {
		t.Fatal("the watcher never reported the regenerated node id")
	}

	if current := fixture.holder.NodeID(); current != next {
		t.Fatalf("NodeID() = %q, want %q after a regeneration", current, next)
	}
}

// TestWatchIdentityIgnoresAnUnchangedFile checks that a rewrite producing the same
// node id does not drop the channel.
//
// The file is rewritten with the identical content, which changes the modification
// time. A watcher that signalled on every write would turn an unrelated touch into a
// reconnect, and a reconnect is a visible interruption for the operator.
func TestWatchIdentityIgnoresAnUnchangedFile(t *testing.T) {
	fixture := newWatchFixture(t)

	ctx, cancel := context.WithCancel(context.Background())
	defer cancel()

	changes := make(chan struct{}, 1)
	go fixture.dialer.watchIdentity(ctx, changes)

	// A rewrite with the same id. The sleep guarantees the modification time differs,
	// so the watcher cannot pass the test by never noticing the write.
	time.Sleep(20 * time.Millisecond)
	if err := SaveIdentity(fixture.identityPath, fixture.firstID); err != nil {
		t.Fatalf("SaveIdentity() = %v, want nil", err)
	}

	if waitForChange(t, changes, 2500*time.Millisecond) {
		t.Fatal("the watcher reported a change for an identical node id, which would drop a working channel")
	}
	if current := fixture.holder.NodeID(); current != fixture.firstID {
		t.Fatalf("NodeID() = %q, want %q", current, fixture.firstID)
	}
}

// TestWatchIdentityKeepsTheOldValueWhenTheFileIsMalformed checks that a corrupt file
// does not replace a working identity.
//
// Adopting a malformed file would leave the Node serving an id it cannot parse, which
// is worse than serving the old one until the operator fixes the file. The old value
// must stay in force and no change must be signalled.
func TestWatchIdentityKeepsTheOldValueWhenTheFileIsMalformed(t *testing.T) {
	fixture := newWatchFixture(t)

	ctx, cancel := context.WithCancel(context.Background())
	defer cancel()

	changes := make(chan struct{}, 1)
	go fixture.dialer.watchIdentity(ctx, changes)

	time.Sleep(20 * time.Millisecond)
	if err := os.WriteFile(fixture.identityPath, []byte("not-a-node-id\n"), 0o600); err != nil {
		t.Fatalf("write a malformed identity file: %v", err)
	}

	if waitForChange(t, changes, 2500*time.Millisecond) {
		t.Fatal("the watcher reported a change for a malformed file")
	}
	if current := fixture.holder.NodeID(); current != fixture.firstID {
		t.Fatalf("NodeID() = %q, want the previous value %q", current, fixture.firstID)
	}
}

// TestWatchIdentityKeepsTheOldValueWhenTheFileDisappears checks that a deleted file
// does not clear the identity.
//
// A Node whose identity file was removed by mistake must keep serving the id it already
// holds rather than start refusing every request, because the operator's next action is
// to restore the file, not to re-provision the Node.
func TestWatchIdentityKeepsTheOldValueWhenTheFileDisappears(t *testing.T) {
	fixture := newWatchFixture(t)

	ctx, cancel := context.WithCancel(context.Background())
	defer cancel()

	changes := make(chan struct{}, 1)
	go fixture.dialer.watchIdentity(ctx, changes)

	time.Sleep(20 * time.Millisecond)
	if err := os.Remove(fixture.identityPath); err != nil {
		t.Fatalf("remove the identity file: %v", err)
	}

	if waitForChange(t, changes, 2500*time.Millisecond) {
		t.Fatal("the watcher reported a change for a missing file")
	}
	if current := fixture.holder.NodeID(); current != fixture.firstID {
		t.Fatalf("NodeID() = %q, want the previous value %q", current, fixture.firstID)
	}
}

// TestWatchIdentityAdoptsARevokedCredentialWithoutDroppingTheChannel checks that a
// changed credential set is adopted and does not signal a channel drop.
//
// The channel was authenticated with the tunnel token, which is a different secret, so
// dropping a working channel because an operator revoked an unrelated caller would be
// a self-inflicted outage.
func TestWatchIdentityAdoptsARevokedCredentialWithoutDroppingTheChannel(t *testing.T) {
	fixture := newWatchFixture(t)

	ctx, cancel := context.WithCancel(context.Background())
	defer cancel()

	changes := make(chan struct{}, 1)
	go fixture.dialer.watchIdentity(ctx, changes)

	replacement, err := security.NewCredentialWithKeyID("second-caller")
	if err != nil {
		t.Fatalf("NewCredentialWithKeyID() = %v, want nil", err)
	}
	time.Sleep(20 * time.Millisecond)
	if err := SaveCredentials(fixture.credentialsPath, []security.Credential{replacement}); err != nil {
		t.Fatalf("SaveCredentials() = %v, want nil", err)
	}

	deadline := time.Now().Add(5 * time.Second)
	for time.Now().Before(deadline) {
		if _, present := fixture.holder.Credentials().Lookup(replacement.KeyID); present {
			break
		}
		time.Sleep(20 * time.Millisecond)
	}
	if _, present := fixture.holder.Credentials().Lookup(replacement.KeyID); !present {
		t.Fatal("the holder never adopted the replacement credential")
	}
	if _, present := fixture.holder.Credentials().Lookup(fixture.firstCredential.KeyID); present {
		t.Fatal("the holder still accepts the revoked credential")
	}
	if waitForChange(t, changes, 2500*time.Millisecond) {
		t.Fatal("a credential change signalled a channel drop, which would be a self-inflicted outage")
	}
}

// TestWatchIdentityKeepsTheOldCredentialsWhenTheFileIsMalformed checks that a corrupt
// credential file does not replace a working set.
//
// Adopting a malformed file would leave the Node accepting nothing, which looks exactly
// like a Node whose policy denies everything.
func TestWatchIdentityKeepsTheOldCredentialsWhenTheFileIsMalformed(t *testing.T) {
	fixture := newWatchFixture(t)

	ctx, cancel := context.WithCancel(context.Background())
	defer cancel()

	changes := make(chan struct{}, 1)
	go fixture.dialer.watchIdentity(ctx, changes)

	time.Sleep(20 * time.Millisecond)
	if err := os.WriteFile(fixture.credentialsPath, []byte("version: 1\ncredentials: []\nunknown_key: 1\n"), 0o600); err != nil {
		t.Fatalf("write a malformed credential file: %v", err)
	}

	if waitForChange(t, changes, 2500*time.Millisecond) {
		t.Fatal("the watcher reported a change for a credential file")
	}
	if _, present := fixture.holder.Credentials().Lookup(fixture.firstCredential.KeyID); !present {
		t.Fatal("the holder dropped the working credential set")
	}
}

// TestWatchIdentityStopsWithTheContext checks that the watcher returns when the
// context ends, because a shutdown must not leave a goroutine polling a file.
func TestWatchIdentityStopsWithTheContext(t *testing.T) {
	fixture := newWatchFixture(t)

	ctx, cancel := context.WithCancel(context.Background())
	changes := make(chan struct{}, 1)

	done := make(chan struct{})
	go func() {
		fixture.dialer.watchIdentity(ctx, changes)
		close(done)
	}()

	cancel()

	select {
	case <-done:
	case <-time.After(5 * time.Second):
		t.Fatal("the watcher did not stop after the context was cancelled")
	}
}

// TestWatchIdentityWithoutAPathReturnsImmediately checks that a dialer with no config
// directory does not start a poll loop.
//
// A dialer built by a test with an empty Config has no file to watch, and a watcher
// that polled anyway would be a goroutine doing nothing for the life of the process.
func TestWatchIdentityWithoutAPathReturnsImmediately(t *testing.T) {
	nodeID, err := security.NewNodeID()
	if err != nil {
		t.Fatalf("NewNodeID() = %v, want nil", err)
	}
	holder := NewIdentityHolder(nodeID, nodeTestCredentialSet(t))
	dispatcher, err := NewDispatcher(nil, holder, security.DefaultReplayWindow, security.DefaultReplayCapacity, slog.New(slog.DiscardHandler))
	if err != nil {
		t.Fatalf("NewDispatcher() = %v, want nil", err)
	}
	dialer, err := NewDialerWithHolder(Config{}, holder, dispatcher, slog.New(slog.DiscardHandler))
	if err != nil {
		t.Fatalf("NewDialerWithHolder() = %v, want nil", err)
	}

	done := make(chan struct{})
	go func() {
		dialer.watchIdentity(context.Background(), make(chan struct{}, 1))
		close(done)
	}()

	select {
	case <-done:
	case <-time.After(2 * time.Second):
		t.Fatal("the watcher polled even though the dialer has no identity path")
	}
}

// TestWatchIdentityDetectsASameLengthRewrite pins the defect that made an
// mtime-and-size stamp unreliable.
//
// A regenerated node id is exactly the same length as the id it replaces, and the
// rewrite can land in the same filesystem timestamp tick. A stamp built from mtime and
// size therefore reported "unchanged" for a file holding a different value, so the
// running Node kept answering to the retired address. Comparing the content is what
// makes this case detectable.
func TestWatchIdentityDetectsASameLengthRewrite(t *testing.T) {
	fixture := newWatchFixture(t)

	ctx, cancel := context.WithCancel(context.Background())
	defer cancel()

	changes := make(chan struct{}, 1)
	go fixture.dialer.watchIdentity(ctx, changes)

	// The replacement is written directly rather than through RegenerateIdentity, so
	// the test controls the encoded length and can assert that the two values are the
	// same size. A size comparison cannot distinguish them.
	next, err := security.NewNodeID()
	if err != nil {
		t.Fatalf("NewNodeID() = %v, want nil", err)
	}
	if len(next) != len(fixture.firstID) {
		t.Fatalf("the fixture ids differ in length (%d and %d), so this test would not exercise the same-length case",
			len(next), len(fixture.firstID))
	}
	if err := SaveIdentity(fixture.identityPath, next); err != nil {
		t.Fatalf("SaveIdentity() = %v, want nil", err)
	}

	if !waitForChange(t, changes, 5*time.Second) {
		t.Fatal("a same-length rewrite was not detected, so the running Node would keep answering to the retired address")
	}

	if current := fixture.holder.NodeID(); current != next {
		t.Fatalf("NodeID() = %q, want %q after a same-length rewrite", current, next)
	}
}

// TestDiscardPendingIdentityChangeDrainsOneSignal checks that a signal left over from a
// disconnected period is removed before the next dial.
//
// Without the drain, a regeneration during a reconnect delay would drop the freshly
// established channel even though it was authenticated with the new id.
func TestDiscardPendingIdentityChangeDrainsOneSignal(t *testing.T) {
	changes := make(chan struct{}, 1)
	changes <- struct{}{}

	discardPendingIdentityChange(changes)

	select {
	case <-changes:
		t.Fatal("a signal survived the drain, so the next channel would be dropped")
	default:
	}
}

// TestDiscardPendingIdentityChangeToleratesAnEmptyChannel checks that the drain does
// not block when nothing is pending, because it runs on every loop iteration.
func TestDiscardPendingIdentityChangeToleratesAnEmptyChannel(t *testing.T) {
	changes := make(chan struct{}, 1)

	done := make(chan struct{})
	go func() {
		discardPendingIdentityChange(changes)
		close(done)
	}()

	select {
	case <-done:
	case <-time.After(2 * time.Second):
		t.Fatal("the drain blocked on an empty channel")
	}
}
