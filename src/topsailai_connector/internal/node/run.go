// Runtime is a started Node: its configuration, its identity, its credentials and its
// authority.
//
// The four are assembled in one place because they are not independent. The authority
// decides what may be served, the identity decides who the Node is, the credentials
// decide who may ask, and the configuration decides where all three come from. A Node
// missing any of them is not a Node that serves a subset; it is a Node that must not
// start.
type Runtime struct {
	config    Config
	holder    *IdentityHolder
	generated bool
	authority *Authority
	logger    *slog.Logger

	// createdCredential is the credential generated by this start, held only until the
	// caller prints it. It is cleared by NewCredential, so a runtime cannot print a
	// secret at a later moment.
	createdCredential *security.Credential

	// statelessCredentials is the credential list a stateless Node resolved in memory.
	// It is nil for a file-backed Node, which reads the list from its file instead.
	// The field exists because the mode has no file to read back from, and the startup
	// summary must still print the credential the operator has to copy.
	statelessCredentials []security.Credential

	// serverURL is the address in force, which the console can replace. It is a field
	// rather than a read of config.ServerURL because the console reports and changes
	// the value the dial loop uses, and a report of the startup value after a
	// successful repoint would read as if the repoint did nothing.
	//
	// It is guarded by serverURLMutex because the console writes it from the goroutine
	// that reads commands while the startup summary and the dial loop read it.
	serverURL      string
	serverURLMutex sync.RWMutex
}

// Open assembles a Runtime from a configuration.
//
// The order is deliberate and every step is fatal:
//
//  1. The identity is loaded or generated first, so its path can be added to the deny
//     list before any scope is opened. A scope opened before the deny list is known
//     would be a scope that can read the Node's own credential.
//  2. The credential file is loaded second, for the same reason: it holds the secrets
//     that authorize every operation, so it must be on the deny list before a scope
//     can serve it.
//  3. The authority is loaded last, so a policy that cannot be served stops the
//     process before anything is advertised.
//
// Open never prints. A generated identifier or credential is reported through
// NewIdentity and NewCredential, so the decision to write a secret to a terminal
// belongs to the process boundary rather than to a library that a test also calls.
//
// A failure at any step closes what was already opened, so a failed start leaves no
// handle and no half-written file behind.
func Open(config Config, logger *slog.Logger) (*Runtime, error) {
	if logger == nil {
		logger = slog.Default()
	}

	// A stateless Node writes nothing, so its identity and its credentials are
	// resolved in memory and no path is formed. The two branches share the same
	// seeds and the same validators, so a stateless Node and a file-backed Node
	// cannot disagree about what a valid node id or a valid credential is.
	//
	// The file-backed branch is unchanged: it still writes the identity and the
	// credential on first start, and the file still wins once it exists.
	var identityPath, credentialsPath string
	var nodeID string
	var generated bool
	var credentials *security.CredentialSet
	var statelessCredentials []security.Credential
	var createdCredential *security.Credential
	var err error

	if config.Stateless {
		nodeID, credentials, statelessCredentials, createdCredential, generated, err = prepareStatelessIdentity()
		if err != nil {
			return nil, err
		}
	} else {
		identityPath = IdentityPath(config.ConfigDir)
		// A build that embedded an identity uses it as the seed for the first write, so
		// the operator knows the address before the artifact leaves the build host. The
		// file still wins once it exists, so `regenerate` keeps working.
		identitySeed, err := embedded.IdentitySeed()
		if err != nil {
			return nil, fmt.Errorf("prepare node identity: %w", err)
		}
		nodeID, generated, err = EnsureIdentityWithSeed(identityPath, identitySeed)
		if err != nil {
			return nil, fmt.Errorf("prepare node identity: %w", err)
		}

		// A Config built by hand rather than by LoadConfig may leave CredentialsPath
		// empty. The default lives inside the config directory, so an empty value is
		// resolved here instead of producing a path with no directory component, which
		// would write the credential file into whatever directory the process happens to
		// run from.
		credentialsPath = config.CredentialsPath
		if credentialsPath == "" {
			credentialsPath = CredentialsPath(config.ConfigDir)
			config.CredentialsPath = credentialsPath
		}

		// The embedded credential is a seed for the same reason the identity is, and the
		// file wins once it exists so `credential remove` keeps working.
		credentialSeed, err := embedded.CredentialSeed()
		if err != nil {
			return nil, fmt.Errorf("prepare node credentials: %w", err)
		}
		credentials, createdCredential, err = EnsureCredentialsWithSeed(credentialsPath, credentialSeed)
		if err != nil {
			return nil, fmt.Errorf("prepare node credentials: %w", err)
		}
	}

	// The deny list names the Node's own files. The identity file and the credential
	// file are the two that must never be readable through a scope: reading the
	// credential file would hand a caller the secret that authorizes every operation on
	// this Node, and reading the identity file would hand it the address.
	//
	// The config directory is listed as well, and that entry is what makes the policy's
	// filesystem-root opt-in safe. A scope rooted at a volume necessarily contains the
	// config directory, so the startup refusal that used to hide it is relaxed when the
	// policy opts in; the deny list then carries the protection, refusing the directory
	// itself and everything inside it.
	denyPaths := []string{identityPath, credentialsPath, config.PolicyPath, config.ConfigDir}

	// A build that compiled the tunnel token in carries a Server-wide secret in its own
	// executable, so the executable joins the deny list. Without this entry a scope that
	// contains the binary serves it, and a caller who reads it recovers a secret that
	// opens a channel to the Server as any Node, not just this one. The entry is added
	// only when the binary actually carries a secret: a normal build discloses nothing
	// by being read, and refusing it would break a legitimate use such as serving the
	// directory the Node was installed in.
	//
	// The path comes from os.Executable rather than from os.Args[0], because os.Args[0]
	// is whatever the launcher typed: a relative path, a symlink or a bare name found on
	// PATH. The deny list compares by file identity, so the resolved path is what makes
	// the comparison correct.
	if embedded.CarriesSecret() {
		executable, err := os.Executable()
		if err != nil {
			return nil, fmt.Errorf("locate the running executable, which carries the tunnel token: %w", err)
		}
		denyPaths = append(denyPaths, executable)
	}

	var authority *Authority
	if config.PolicyBytes != nil {
		authority, err = LoadAuthorityBytes(config.PolicyBytes, denyPaths, config.ConfigDir)
	} else {
		authority, err = LoadAuthority(config.PolicyPath, denyPaths, config.ConfigDir)
	}
	if err != nil {
		return nil, fmt.Errorf("load authority: %w", err)
	}

	runtime := &Runtime{
		config:               config,
		serverURL:            config.ServerURL,
		holder:               NewIdentityHolder(nodeID, credentials),
		generated:            generated,
		authority:            authority,
		logger:               logger,
		statelessCredentials: statelessCredentials,
	}
	// The generated credential is kept only until the caller prints it. It is not
	// stored on the runtime, because a runtime that held it would be a runtime that
	// could print a secret at any later moment.
	runtime.createdCredential = createdCredential
	return runtime, nil
}

// prepareStatelessIdentity resolves the identity and the credentials without
// touching the filesystem.
//
// The order of preference is the one the operator asked for: a value compiled into
// the binary is used when it is present, and a value is generated in memory when it
// is not. Nothing is written either way, so the mode works on a filesystem the
// process cannot write to.
//
// The generated credential is returned separately so the caller can print it once,
// exactly as the file-backed path does. A stateless Node that generated a credential
// and did not print it would be a Node nobody can reach, because there is no file to
// read it back from.
//
// The identity is reported the same way, and the distinction it carries is the one the
// startup summary needs: a random id is new on every start, while an embedded id is the
// same value every time. Announcing an embedded id as new would be false, and an
// operator who believed it would expect the address to change on the next restart.
//
// A malformed embedded value is an error rather than a fallback to a random one. A
// packaging mistake that silently produced a different secret would hand the operator
// a value that does not authenticate, and the failure would appear on the recipient's
// machine rather than at packaging time.
func prepareStatelessIdentity() (nodeID string, credentials *security.CredentialSet, list []security.Credential, created *security.Credential, identityCreated bool, err error) {
	identitySeed, err := embedded.IdentitySeed()
	if err != nil {
		return "", nil, nil, nil, false, fmt.Errorf("prepare node identity: %w", err)
	}
	if identitySeed == "" {
		identitySeed, err = security.NewNodeID()
		if err != nil {
			return "", nil, nil, nil, false, fmt.Errorf("prepare node identity: %w", err)
		}
		identityCreated = true
	}

	credentialSeed, err := embedded.CredentialSeed()
	if err != nil {
		return "", nil, nil, nil, false, fmt.Errorf("prepare node credentials: %w", err)
	}
	generated := false
	if credentialSeed.KeyID == "" {
		credentialSeed, err = security.NewCredential()
		if err != nil {
			return "", nil, nil, nil, false, fmt.Errorf("prepare node credentials: %w", err)
		}
		generated = true
	}

	// The list is returned alongside the set because CredentialSet deliberately
	// exposes no way to read a secret back: it offers Lookup, Len and KeyIDs only.
	// A stateless Node has no file to re-read, so the list it built is the only
	// record of the credential, and the startup summary needs it to print the
	// secret the operator must copy.
	list = []security.Credential{credentialSeed}
	set, err := security.NewCredentialSet(list)
	if err != nil {
		return "", nil, nil, nil, false, fmt.Errorf("prepare node credentials: %w", err)
	}
	if generated {
		created = &credentialSeed
	}
	return identitySeed, set, list, created, identityCreated, nil
}

// NewIdentity returns the node id and whether this start created it.
//
// The second result exists so the caller announces the identifier exactly once, at the
// moment it is created. In a file-backed Node "created" means "the file did not exist
// and this start wrote it", and the value may be a random one this start generated or a
// seed the build embedded; the caller cannot tell the two apart and does not need to,
// because both are recorded in the file from then on.
//
// In a stateless Node "created" means "this start generated a random value", because
// nothing is recorded anywhere. An embedded value is not created by the start: it is the
// same value on every start, so announcing it as new would tell the operator to expect a
// different address after a restart.
func (r *Runtime) NewIdentity() (string, bool) {
	return r.holder.NodeID(), r.generated
}

// NewCredential returns the credential generated by this start, or nil.
//
// The value is returned once and never stored, so a caller that prints it is the only
// place a secret reaches a terminal. A runtime that kept it would be a runtime that
// could print a secret at any later moment, which is the leak the design forbids.
func (r *Runtime) NewCredential() *security.Credential {
	credential := r.createdCredential
	r.createdCredential = nil
	return credential
}

// CredentialList returns the credentials this Node accepts, for reporting.
//
// A file-backed Node reads them from the file, because the runtime deliberately
// holds no secret: a runtime that could render a secret would be a runtime that
// could print one at any later moment.
//
// A stateless Node has no file to read, so the list is the one it resolved in
// memory. That is a deliberate exception to the no-secret-on-the-runtime rule, and
// it is confined to the mode that has no other way to answer the question: without
// it the startup summary could not print the credential the operator must copy, and
// there is no file to read it back from later.
func (r *Runtime) CredentialList() ([]security.Credential, error) {
	if r.config.CredentialsPath != "" {
		return LoadCredentialList(r.config.CredentialsPath)
	}
	return r.statelessCredentials, nil
}

// ReplaceNodeID installs a new node id and reports whether it differs from the one in
// force.
//
// A file-backed Node also writes the identity file, so the console and
// `connector-node regenerate` agree about what is in force and a restart keeps the new
// address. A stateless Node writes nothing, because writing is the one thing the mode
// forbids; the value lives in memory and is lost when the process exits.
//
// The file is written before the holder is updated, so a write that fails leaves the
// Node serving the identity it can actually prove. The reverse order would publish an
// address the Node cannot reproduce after a restart, which is a Node that answers to a
// name it will forget.
func (r *Runtime) ReplaceNodeID(nodeID string) (bool, error) {
	if err := security.ValidateNodeID(nodeID); err != nil {
		return false, err
	}
	if r.holder.NodeID() == nodeID {
		return false, nil
	}

	if !r.config.Stateless {
		path := IdentityPath(r.config.ConfigDir)
		if err := SaveIdentity(path, nodeID); err != nil {
			return false, fmt.Errorf("write the identity file: %w", err)
		}
	}

	return r.holder.ReplaceNodeID(nodeID), nil
}

// ReplaceCredentials installs a new credential set and reports whether it differs from
// the one in force.
//
// The set is built from the list before anything is written, so a list that cannot form
// a valid set is refused without touching the file or the holder. A half-applied
// rotation would leave the Node accepting a secret the operator believes is retired.
//
// A file-backed Node writes the credential file, so a restart keeps the change. A
// stateless Node keeps the set in memory only.
//
// The comparison is on the key identifiers, which is the same rule the holder uses. A
// rotation that keeps the key id and replaces the secret is therefore reported as
// unchanged by the holder, and that is why this method compares the sets itself before
// deciding: a rotation must still be applied and still be written.
func (r *Runtime) ReplaceCredentials(list []security.Credential) error {
	set, err := security.NewCredentialSet(list)
	if err != nil {
		return err
	}

	if !r.config.Stateless {
		path := r.config.CredentialsPath
		if path == "" {
			path = CredentialsPath(r.config.ConfigDir)
		}
		if err := SaveCredentials(path, list); err != nil {
			return fmt.Errorf("write the credential file: %w", err)
		}
	}

	// The holder reports "unchanged" when the key identifiers match, which is the
	// correct answer for the watcher and the wrong answer here: a rotation keeps the
	// identifier and replaces the secret, so the set must be installed even when the
	// identifiers are identical. The store is unconditional for that reason.
	r.holder.credentials.Store(set)
	r.statelessCredentials = list
	return nil
}

// IdentityHolder returns the holder the Node serves from.
//
// The process passes this one holder to both the dispatcher and the dialer, so a
// regenerated identifier is adopted by the component that announces the identity and
// by the component that checks it at the same moment. Two holders would let the Node
// announce one identity and check another.
func (r *Runtime) IdentityHolder() *IdentityHolder {
	return r.holder
}

// Close releases the runtime's resources. It is safe to call more than once.
func (r *Runtime) Close() error {
	if r == nil {
		return nil
	}
	return r.authority.Close()
}

// IdentityID returns the public half of the identity, which is the value that may be
// logged, audited and routed on.
func (r *Runtime) IdentityID() string {
	return r.holder.NodeID()
}

// Authority returns the Node's permission state.
func (r *Runtime) Authority() *Authority {
	return r.authority
}

// Config returns the configuration the runtime was built from.
func (r *Runtime) Config() Config {
	config := r.config
	// The address is reported from the field in force rather than from the value the
	// process started with, so `show config` and `show status` agree with the console
	// after a repoint. Every other field is immutable after Open, so only this one is
	// substituted.
	config.ServerURL = r.ServerURL()
	return config
}

// ServerURL returns the address in force.
func (r *Runtime) ServerURL() string {
	r.serverURLMutex.RLock()
	defer r.serverURLMutex.RUnlock()
	return r.serverURL
}

// ReplaceServerURL validates and stores a new Server address.
//
// The value is validated by the same function the startup path uses, so the console
// cannot accept an address that `run` would refuse. A second validator here would be a
// second definition of an acceptable address, and the two would eventually disagree
// about which values are allowed.
//
// It returns the previous address so the caller can report what changed, and it does
// not drop the live channel: dropping is the caller's decision, because a repoint and
// a reconnect are separate acts with separate consequences.
func (r *Runtime) ReplaceServerURL(value string) (string, error) {
	if err := validateServerURL(value); err != nil {
		return "", err
	}
	r.serverURLMutex.Lock()
	previous := r.serverURL
	r.serverURL = value
	r.serverURLMutex.Unlock()
	return previous, nil
}

// Report logs one startup line describing what the Node will serve.
//
// The report names the scopes, the identity and the public credential key identifiers,
// and never a secret: the identity is printed through its redacted form and the
// configuration through its redacted form, so a field added later cannot leak by being
// forgotten here.
//
// A scope whose directory did not exist at startup is named in a separate WARN line
// with its path. The ready line still lists it, because the scope is defined and
// advertised; the warning is what tells the operator that this scope serves nothing
// until the directory exists and the Node is restarted. Without the warning a degraded
// scope would look exactly like a working one until a caller reported not_found.
func (r *Runtime) Report() {
	names := r.authority.ScopeNames()
	scopes := make([]string, 0, len(names))
	absent := make([]string, 0, len(names))
	for _, name := range names {
		scopes = append(scopes, string(name))
		scope, ok := r.authority.Scope(name)
		if !ok || !scope.Absent() {
			continue
		}
		absent = append(absent, string(name))
		r.logger.Warn("connector-node scope directory does not exist",
			"scope", string(name),
			"path", scope.ResolvedPath(),
			"effect", "every request on this scope answers not_found until the directory exists and the node restarts",
		)
	}
	r.logger.Info("connector-node ready",
		"node_id", r.holder.NodeID(),
		"scopes", scopes,
		"absent_scopes", absent,
		"client_key_ids", r.holder.Credentials().KeyIDs(),
		"config", r.config.Redacted(),
	)
}
