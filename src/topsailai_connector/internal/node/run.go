package node

import (
	"fmt"
	"log/slog"

	"topsailai_connector/internal/security"
)

// Runtime is a started Node: its configuration, its identity and its authority.
//
// The three are assembled in one place because they are not independent. The
// authority decides what may be served, the identity decides who the Node is, and
// the configuration decides where both come from. A Node missing any of the three
// is not a Node that serves a subset; it is a Node that must not start.
type Runtime struct {
	config    Config
	holder    *IdentityHolder
	generated bool
	authority *Authority
	logger    *slog.Logger
}

// Open assembles a Runtime from a configuration.
//
// The order is deliberate and every step is fatal:
//
//  1. The identity is loaded or generated first, so its path can be added to the
//     deny list before any scope is opened. A scope opened before the deny list is
//     known would be a scope that can read the Node's own credential.
//  2. The authority is loaded second, so a policy that cannot be served stops the
//     process before anything is advertised.
//
// Open never prints. A generated pair is reported through NewIdentity, so the
// decision to write a credential to a terminal belongs to the process boundary
// rather than to a library that a test also calls.
//
// A failure at any step closes what was already opened, so a failed start leaves
// no handle and no half-written file behind.
func Open(config Config, logger *slog.Logger) (*Runtime, error) {
	if logger == nil {
		logger = slog.Default()
	}

	identityPath := IdentityPath(config.ConfigDir)
	identity, generated, err := EnsureIdentity(identityPath)
	if err != nil {
		return nil, fmt.Errorf("prepare node identity: %w", err)
	}

	// The deny list names the Node's own files. The identity file is the one that
	// must never be readable through a scope, because reading it would hand a
	// caller the credential that authorizes every operation on this Node.
	denyPaths := []string{identityPath, config.PolicyPath}

	authority, err := LoadAuthority(config.PolicyPath, denyPaths)
	if err != nil {
		return nil, fmt.Errorf("load authority: %w", err)
	}

	return &Runtime{
		config:    config,
		holder:    NewIdentityHolder(identity),
		generated: generated,
		authority: authority,
		logger:    logger,
	}, nil
}

// NewIdentity returns the identity and whether it was generated by this start.
//
// The second result exists so the caller prints the pair exactly once, at the
// moment it is created. Printing it on every start would put a credential into a
// log on every start, which is the leak the design forbids.
func (r *Runtime) NewIdentity() (security.NodeIdentity, bool) {
	return r.holder.Current(), r.generated
}

// IdentityHolder returns the holder the Node serves from.
//
// The process passes this one holder to both the dispatcher and the dialer, so a
// regenerated pair is adopted by the component that announces the identity and by
// the component that checks it at the same moment. Two holders would let the Node
// announce one identity and check another.
func (r *Runtime) IdentityHolder() *IdentityHolder {
	return r.holder
}

// Close releases the runtime's resources. It is safe to call more than once.
func (r *Runtime) Close() error {
	if r == nil {
		return nil
	}
	return r.authority.Close()
}

// IdentityID returns the public half of the identity, which is the value that may
// be logged, audited and routed on.
func (r *Runtime) IdentityID() string {
	return r.holder.Current().ID
}

// Authority returns the Node's permission state.
func (r *Runtime) Authority() *Authority {
	return r.authority
}

// Config returns the configuration the runtime was built from.
func (r *Runtime) Config() Config {
	return r.config
}

// Report logs one startup line describing what the Node will serve.
//
// The report names the scopes and the identity, and never a secret: the identity
// is printed through its redacted form and the configuration through its redacted
// form, so a field added later cannot leak by being forgotten here.
func (r *Runtime) Report() {
	names := r.authority.ScopeNames()
	scopes := make([]string, 0, len(names))
	for _, name := range names {
		scopes = append(scopes, string(name))
	}
	r.logger.Info("connector-node ready",
		"node_id", r.holder.Current().ID,
		"scopes", scopes,
		"config", r.config.Redacted(),
	)
}
