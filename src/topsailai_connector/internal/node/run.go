package node

import (
	"fmt"
	"log/slog"
	"os"

	"topsailai_connector/internal/node/embedded"
	"topsailai_connector/internal/security"
)

// Runtime is a started Node: its configuration, its identity, its credentials and its
// authority.
//
// The four are assembled in one place because they are not independent. The authority
// decides what may be served, the identity decides who the Node is, the credentials
// decide who may ask, and the configuration decides where all three come from. A Node
// missing any of them is not a Node that serves a subset; it is a Node that must not
// start.
type Runtime struct {
	config    Config
	holder    *IdentityHolder
	generated bool
	authority *Authority
	logger    *slog.Logger

	// createdCredential is the credential generated by this start, held only until the
	// caller prints it. It is cleared by NewCredential, so a runtime cannot print a
	// secret at a later moment.
	createdCredential *security.Credential
}

// Open assembles a Runtime from a configuration.
//
// The order is deliberate and every step is fatal:
//
//  1. The identity is loaded or generated first, so its path can be added to the deny
//     list before any scope is opened. A scope opened before the deny list is known
//     would be a scope that can read the Node's own credential.
//  2. The credential file is loaded second, for the same reason: it holds the secrets
//     that authorize every operation, so it must be on the deny list before a scope
//     can serve it.
//  3. The authority is loaded last, so a policy that cannot be served stops the
//     process before anything is advertised.
//
// Open never prints. A generated identifier or credential is reported through
// NewIdentity and NewCredential, so the decision to write a secret to a terminal
// belongs to the process boundary rather than to a library that a test also calls.
//
// A failure at any step closes what was already opened, so a failed start leaves no
// handle and no half-written file behind.
func Open(config Config, logger *slog.Logger) (*Runtime, error) {
	if logger == nil {
		logger = slog.Default()
	}

	identityPath := IdentityPath(config.ConfigDir)
	nodeID, generated, err := EnsureIdentity(identityPath)
	if err != nil {
		return nil, fmt.Errorf("prepare node identity: %w", err)
	}

	// A Config built by hand rather than by LoadConfig may leave CredentialsPath
	// empty. The default lives inside the config directory, so an empty value is
	// resolved here instead of producing a path with no directory component, which
	// would write the credential file into whatever directory the process happens to
	// run from.
	credentialsPath := config.CredentialsPath
	if credentialsPath == "" {
		credentialsPath = CredentialsPath(config.ConfigDir)
		config.CredentialsPath = credentialsPath
	}

	credentials, createdCredential, err := EnsureCredentials(credentialsPath)
	if err != nil {
		return nil, fmt.Errorf("prepare node credentials: %w", err)
	}

	// The deny list names the Node's own files. The identity file and the credential
	// file are the two that must never be readable through a scope: reading the
	// credential file would hand a caller the secret that authorizes every operation on
	// this Node, and reading the identity file would hand it the address.
	//
	// The config directory is listed as well, and that entry is what makes the policy's
	// filesystem-root opt-in safe. A scope rooted at a volume necessarily contains the
	// config directory, so the startup refusal that used to hide it is relaxed when the
	// policy opts in; the deny list then carries the protection, refusing the directory
	// itself and everything inside it.
	denyPaths := []string{identityPath, credentialsPath, config.PolicyPath, config.ConfigDir}

	// A build that compiled the tunnel token in carries a Server-wide secret in its own
	// executable, so the executable joins the deny list. Without this entry a scope that
	// contains the binary serves it, and a caller who reads it recovers a secret that
	// opens a channel to the Server as any Node, not just this one. The entry is added
	// only when the binary actually carries a secret: a normal build discloses nothing
	// by being read, and refusing it would break a legitimate use such as serving the
	// directory the Node was installed in.
	//
	// The path comes from os.Executable rather than from os.Args[0], because os.Args[0]
	// is whatever the launcher typed: a relative path, a symlink or a bare name found on
	// PATH. The deny list compares by file identity, so the resolved path is what makes
	// the comparison correct.
	if embedded.CarriesSecret() {
		executable, err := os.Executable()
		if err != nil {
			return nil, fmt.Errorf("locate the running executable, which carries the tunnel token: %w", err)
		}
		denyPaths = append(denyPaths, executable)
	}

	var authority *Authority
	if config.PolicyBytes != nil {
		authority, err = LoadAuthorityBytes(config.PolicyBytes, denyPaths, config.ConfigDir)
	} else {
		authority, err = LoadAuthority(config.PolicyPath, denyPaths, config.ConfigDir)
	}
	if err != nil {
		return nil, fmt.Errorf("load authority: %w", err)
	}

	runtime := &Runtime{
		config:    config,
		holder:    NewIdentityHolder(nodeID, credentials),
		generated: generated,
		authority: authority,
		logger:    logger,
	}
	// The generated credential is kept only until the caller prints it. It is not
	// stored on the runtime, because a runtime that held it would be a runtime that
	// could print a secret at any later moment.
	runtime.createdCredential = createdCredential
	return runtime, nil
}

// NewIdentity returns the node id and whether it was generated by this start.
//
// The second result exists so the caller prints the identifier exactly once, at the
// moment it is created. Printing it on every start would fill a log with an address
// that never changes.
func (r *Runtime) NewIdentity() (string, bool) {
	return r.holder.NodeID(), r.generated
}

// NewCredential returns the credential generated by this start, or nil.
//
// The value is returned once and never stored, so a caller that prints it is the only
// place a secret reaches a terminal. A runtime that kept it would be a runtime that
// could print a secret at any later moment, which is the leak the design forbids.
func (r *Runtime) NewCredential() *security.Credential {
	credential := r.createdCredential
	r.createdCredential = nil
	return credential
}

// IdentityHolder returns the holder the Node serves from.
//
// The process passes this one holder to both the dispatcher and the dialer, so a
// regenerated identifier is adopted by the component that announces the identity and
// by the component that checks it at the same moment. Two holders would let the Node
// announce one identity and check another.
func (r *Runtime) IdentityHolder() *IdentityHolder {
	return r.holder
}

// Close releases the runtime's resources. It is safe to call more than once.
func (r *Runtime) Close() error {
	if r == nil {
		return nil
	}
	return r.authority.Close()
}

// IdentityID returns the public half of the identity, which is the value that may be
// logged, audited and routed on.
func (r *Runtime) IdentityID() string {
	return r.holder.NodeID()
}

// Authority returns the Node's permission state.
func (r *Runtime) Authority() *Authority {
	return r.authority
}

// Config returns the configuration the runtime was built from.
func (r *Runtime) Config() Config {
	return r.config
}

// Report logs one startup line describing what the Node will serve.
//
// The report names the scopes, the identity and the public credential key identifiers,
// and never a secret: the identity is printed through its redacted form and the
// configuration through its redacted form, so a field added later cannot leak by being
// forgotten here.
//
// A scope whose directory did not exist at startup is named in a separate WARN line
// with its path. The ready line still lists it, because the scope is defined and
// advertised; the warning is what tells the operator that this scope serves nothing
// until the directory exists and the Node is restarted. Without the warning a degraded
// scope would look exactly like a working one until a caller reported not_found.
func (r *Runtime) Report() {
	names := r.authority.ScopeNames()
	scopes := make([]string, 0, len(names))
	absent := make([]string, 0, len(names))
	for _, name := range names {
		scopes = append(scopes, string(name))
		scope, ok := r.authority.Scope(name)
		if !ok || !scope.Absent() {
			continue
		}
		absent = append(absent, string(name))
		r.logger.Warn("connector-node scope directory does not exist",
			"scope", string(name),
			"path", scope.ResolvedPath(),
			"effect", "every request on this scope answers not_found until the directory exists and the node restarts",
		)
	}
	r.logger.Info("connector-node ready",
		"node_id", r.holder.NodeID(),
		"scopes", scopes,
		"absent_scopes", absent,
		"client_key_ids", r.holder.Credentials().KeyIDs(),
		"config", r.config.Redacted(),
	)
}
